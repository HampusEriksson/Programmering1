a = 17
b = 3
# Addition
c = a + b
print(c)
# Subtraktion
d = a - b
print(d)
# Multiplikation
print(a * b)
# Division
print(a / 3)
# Upphöjt i - **
print(3**3)

# Roten ur
print(9**0.5)

# Floor division x // y - dela x på y, runda ner till heltal
print(17 // 5)
print(21 // 5)
print(230 // 60)

# Modulo x % y - hur mycket rest när x delas med y
print(17 % 5)  # 2
print(21 % 5)  # 1
print(230 % 60)

# Jämnt tal
print(6 % 2)

# Udda
print(7 % 2)
